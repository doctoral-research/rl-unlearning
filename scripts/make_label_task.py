"""Generate a human labelling task for a corpus entry.

Corpus verdicts are currently assigned by whoever wrote the grammar,
which makes expressibility a statement about the author's confidence
rather than about the language. Reference labels break that: someone who
did not write the scenario marks where the behaviour occurs, and the
specification is scored against those marks.

This produces the file for them to fill in. It deliberately leaves every
`label:` null. A label generated by the same process that produced the
specification measures nothing, so the blanks have to be filled by a
person who is shown the description and the trajectory, and NOT the
scenario YAML.

    python scripts/make_label_task.py --entry fourrooms.avoid_bottom_right \
        --episodes 10 --out benchmark/labels/fourrooms.avoid_bottom_right.yaml

Then, once it is filled in, add to the corpus entry:

    labels: benchmark/labels/fourrooms.avoid_bottom_right.yaml
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from scenarios.corpus import (                                   # noqa: E402
    load_corpus, register_contrib_providers, resolve_views,
)


def collect(env, view, n_episodes, max_steps, seed, policy=None):
    """Roll out episodes, recording the view's features per step."""
    episodes = []
    for ep in range(n_episodes):
        obs, info = env.reset(seed=seed + ep)
        steps = []
        for t in range(max_steps):
            feats = view.extract(obs=obs, info=info, env=env)
            action = (env.action_space.sample() if policy is None
                      else policy(obs))
            steps.append((list(map(float, feats)), action))
            obs, _r, term, trunc, info = env.step(action)
            if term or trunc:
                break
        episodes.append(steps)
    return episodes


from scenarios.rollouts import build_policy_env  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--entry", required=True, help="corpus entry id")
    ap.add_argument("--corpus", default="benchmark/behaviours")
    ap.add_argument("--episodes", type=int, default=10)
    ap.add_argument("--max-steps", type=int, default=100)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", required=True)
    ap.add_argument("--checkpoint", default=None,
                    help="policy checkpoint; without it actions are random "
                         "and rare behaviours never appear")
    ap.add_argument("--env-overrides", default=None,
                    help="comma-separated hydra overrides, e.g. env=fourrooms")
    args = ap.parse_args()

    register_contrib_providers()
    entries = {e.id: e for e in load_corpus(args.corpus)}
    if args.entry not in entries:
        raise SystemExit(f"unknown entry {args.entry!r}; "
                         f"have {len(entries)} entries")
    entry = entries[args.entry]
    view = resolve_views([entry.domain]).get(entry.domain)
    if view is None:
        raise SystemExit(
            f"no feature view resolves for {entry.domain}; a labelling task "
            "needs named features for the annotator to read")

    policy = None
    if args.checkpoint:
        env, policy = build_policy_env(args.env_overrides, args.checkpoint)
    else:
        import gymnasium as gym
        if entry.domain.startswith("MiniGrid-"):
            import minigrid                                      # noqa: F401
        elif entry.domain.startswith("Foraging-"):
            import lbforaging                                    # noqa: F401
        env = gym.make(entry.domain)

    episodes = collect(env, view, args.episodes, args.max_steps, args.seed,
                       policy=policy)

    doc = {
        "entry": entry.id,
        "env": entry.domain,
        "description": entry.description,
        "annotator": None,
        "instructions": (
            "For each step set label: true if the behaviour described above "
            "is occurring AT THAT STEP, otherwise false. Judge only from the "
            "description and the feature values. Do not read the scenario "
            "YAML: the point is an independent reading."),
        "features": list(view.names),
        "episodes": [
            {"id": i,
             "steps": [
                 {"t": t,
                  **{n: round(v, 4) for n, v in zip(view.names, feats)},
                  "action": int(a) if np.isscalar(a) else [float(x) for x in a],
                  "label": None}
                 for t, (feats, a) in enumerate(steps)]}
            for i, steps in enumerate(episodes)
        ],
    }

    # Warn when the sample cannot contain the behaviour. A specification
    # firing is NOT evidence that the described behaviour occurs: for a
    # `partial` entry the specification is an approximation by
    # construction, so it can fire steadily on rollouts in which the real
    # behaviour never happens. Two annotators caught exactly that here,
    # on episodes too short to contain a landing.
    n_term = sum(1 for e in episodes if len(e) < args.max_steps)
    if n_term == 0:
        print(f"  WARNING: no episode terminated within --max-steps "
              f"({args.max_steps}). Every episode is a truncated prefix, so "
              "any behaviour defined by how an episode ENDS is absent from "
              "this sample.")
    const = [n for i, n in enumerate(view.names)
             if len({round(float(s[0][i]), 6) for s in
                     [st for ep in episodes for st in ep]}) == 1]
    if const:
        print(f"  WARNING: feature(s) constant across the whole sample: "
              f"{', '.join(const)}. Anything defined by them is "
              "unobservable here.")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(yaml.safe_dump(doc, sort_keys=False, width=100))
    n = sum(len(e["steps"]) for e in doc["episodes"])
    print(f"wrote {out}")
    print(f"  entry    : {entry.id}")
    print(f"  view     : {view.provenance}  ({', '.join(view.names)})")
    print(f"  episodes : {len(doc['episodes'])}")
    print(f"  steps    : {n} to label")
    print("\nGive this file to someone who has NOT seen the scenario YAML.")


if __name__ == "__main__":
    main()
